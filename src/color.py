    YELLOW = 0xFFFFFF00
    CYBER_YELLOW = 0xFFFFD300
    BLACK = 0xFF000000
    WHITE = 0xFFFFFFFF
    ST_WHITE = 0x66FFFFFF
    LT_WHITE = 0x22FFFFFF
    
    CYAN = 0xFF00FFFF
    MAGENTA = 0xFFFF00FF
