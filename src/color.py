def color_to_sdl_color(color: Color) -> SDL_Color:
    b = color & 0xFF
    g = (color >> 8) & 0xFF
    r = (color >> 16) & 0xFF
    a = (color >> 24) & 0xFF
    return SDL_Color(r, g, b, a)
